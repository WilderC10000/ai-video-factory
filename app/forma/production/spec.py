"""The Project #3 production spec: checkpoint-first planning in one project.json.

A project is a chain of CHECKPOINTS (visible construction states, each an approved still) joined by
SHOTS (the work between two consecutive checkpoints). A shot's complexity decides its clip count (doctrine
production lesson 11): simple 1, medium 2, complex up to 3, static 0 (the end checkpoint still is the
phase-completion edit - no video). A shot with N clips gets N-1 intermediate stills, so every clip runs
first/last frame between two approved stills and clips are joined by hard cuts in the edit:

    cp02_still --s02_clip1--> s02_mid1_still --s02_clip2--> s02_mid2_still --s02_clip3--> cp03_still

Keys are deterministic from the spec, so the manifest, the stills folder and the studio agree on names.

Stills are GENERATED by default (`"stills": {"source": "generate"}`, app.forma.production.still_gen): the first
still is text-to-image from its brief; every later still is an image EDIT of the previous still in production
order (its exact approved pixels). A manual upload (e.g. a ChatGPT image) is an optional override for any still;
`"source": "manual"` turns generation off for the whole project.
"""
import json
from dataclasses import dataclass, field
from pathlib import Path

from app.forma.doctrine import SHOT_CLASSES

COMPLEXITY_CLIPS = {"simple": 1, "medium": 2, "complex": 3, "static": 0}
STILL_EXTENSIONS = (".jpg", ".jpeg", ".png", ".webp")
STILL_SOURCES = ("generate", "manual")
# Proposed default: the cheap Nano Banana tier (Pro is the proven fallback - see still_gen.STILL_MODELS).
DEFAULT_GENERATE_MODEL = "fal-ai/nano-banana"
DEFAULT_EDIT_MODEL = "fal-ai/nano-banana/edit"


class SpecError(Exception):
    pass


@dataclass(frozen=True)
class Checkpoint:
    id: str  # "cp01"
    title: str
    state: str  # what is visibly true in this still
    camera: str  # key of ProjectSpec.cameras
    built: tuple[str, ...] = ()  # every construction element present (cumulative)
    materials: dict[str, str] = field(default_factory=dict)  # element -> where its material visibly comes from
    tools_in_view: tuple[str, ...] = ()
    action: str = ""  # what the builder is visibly doing in this still
    not_yet: tuple[str, ...] = ()  # extra "must not appear yet" items beyond later checkpoints' elements

    @property
    def still_key(self) -> str:
        return f"{self.id}_still"


@dataclass(frozen=True)
class Beat:
    task: str  # one local physical task
    location: str  # where in the frame / work area
    duration_seconds: int = 3
    after: str = ""  # the visible state once this beat's work is done (the intermediate still that follows it)


@dataclass(frozen=True)
class Shot:
    id: str  # "s02"
    from_cp: str
    to_cp: str
    title: str
    complexity: str  # simple | medium | complex | static
    shot_class: str  # doctrine.SHOT_CLASSES key
    beats: tuple[Beat, ...] = ()
    camera_moves: bool = False
    proof: bool = False  # the first clip of an unproven route: allowed only as a proof
    model: str | None = None  # explicit fal model (must be an allowed route); None = routing decides
    hold: str = ""  # a planning concern to resolve first: while set, the shot's clips are blocked (stills are not)

    @property
    def clip_count(self) -> int:
        return len(self.beats) if self.complexity != "static" else 0

    def clip_keys(self) -> list[str]:
        return [f"{self.id}_clip{n}" for n in range(1, self.clip_count + 1)]

    def mid_still_keys(self) -> list[str]:
        return [f"{self.id}_mid{n}_still" for n in range(1, self.clip_count)]


@dataclass(frozen=True)
class Clip:
    key: str
    shot: Shot
    n: int
    beat: Beat
    start_still: str
    end_still: str


@dataclass(frozen=True)
class Still:
    key: str
    label: str
    kind: str  # "checkpoint" | "intermediate"
    brief: str
    checkpoint: str | None = None
    shot: str | None = None


@dataclass(frozen=True)
class StillsConfig:
    source: str = "generate"  # generate (default) | manual (uploads only)
    generate_model: str = DEFAULT_GENERATE_MODEL  # the first still: text-to-image (or edit of its references)
    edit_model: str = DEFAULT_EDIT_MODEL  # every later still: edit of the previous approved still
    per_still_max_usd: float = 0.20  # the most one approval may spend on one still call
    first_still_references: tuple[str, ...] = ()  # optional images (relative to the project dir) for the first still
    proof_stills: tuple[str, ...] = ()  # non-empty = a proof: ONLY these stills may be generated for now
    model_overrides: dict[str, str] = field(default_factory=dict)  # still key -> model (e.g. a harder removal)
    frame_size: tuple[int, int] | None = None  # every still is scaled to this (w, h) so clip frames always match

    def model_for(self, still_key: str, is_first: bool) -> str:
        return self.model_overrides.get(still_key) or (self.generate_model if is_first else self.edit_model)


@dataclass
class ProjectSpec:
    slug: str
    name: str
    status: str  # template | planning | production | frozen
    budget_cap_usd: float
    per_clip_max_usd: float
    concept: dict | None = None
    bibles: dict[str, str] = field(default_factory=dict)  # location / structure / builder / materials
    cameras: dict[str, str] = field(default_factory=dict)
    checkpoints: list[Checkpoint] = field(default_factory=list)
    shots: list[Shot] = field(default_factory=list)
    stills_config: StillsConfig = field(default_factory=StillsConfig)

    # --- derived -------------------------------------------------------------------------------------
    def checkpoint(self, cp_id: str) -> Checkpoint:
        for cp in self.checkpoints:
            if cp.id == cp_id:
                return cp
        raise SpecError(f"Unknown checkpoint {cp_id!r}")

    def clips(self) -> list[Clip]:
        out = []
        for shot in self.shots:
            chain = [self.checkpoint(shot.from_cp).still_key, *shot.mid_still_keys(),
                     self.checkpoint(shot.to_cp).still_key]
            for n, (key, beat) in enumerate(zip(shot.clip_keys(), shot.beats), 1):
                out.append(Clip(key, shot, n, beat, chain[n - 1], chain[n]))
        return out

    def clip(self, key: str) -> Clip:
        for clip in self.clips():
            if clip.key == key:
                return clip
        raise SpecError(f"Unknown clip {key!r}")

    def stills(self) -> list[Still]:
        """Every manual still, in production order (a shot's intermediates before its end checkpoint)."""
        out: list[Still] = []
        seen = set()
        shots_into = {s.to_cp: s for s in self.shots}
        for cp in self.checkpoints:
            shot = shots_into.get(cp.id)
            if shot is not None:
                for n, key in enumerate(shot.mid_still_keys(), 1):
                    out.append(Still(key, f"{shot.id} intermediate {n}/{shot.clip_count - 1} - {shot.title}",
                                     "intermediate", self._mid_brief(shot, n), shot=shot.id))
            if cp.still_key not in seen:
                out.append(Still(cp.still_key, f"{cp.id.upper()} - {cp.title}", "checkpoint",
                                 self._cp_brief(cp), checkpoint=cp.id))
                seen.add(cp.still_key)
        return out

    def still_keys(self) -> set[str]:
        return {s.key for s in self.stills()}

    def edit_source(self, still_key: str) -> str | None:
        """The still a generated still is an edit of: the previous still in production order (None = the first
        still, generated from text). For an intermediate that is the shot's start checkpoint or the previous
        intermediate; for a checkpoint after a static time jump or a camera change it is the previous checkpoint."""
        keys = [s.key for s in self.stills()]
        i = keys.index(still_key)
        return keys[i - 1] if i else None

    def still_camera(self, still_key: str) -> str:
        """The camera a still is seen from (an intermediate keeps its shot's start camera)."""
        still = next(s for s in self.stills() if s.key == still_key)
        if still.checkpoint:
            return self.checkpoint(still.checkpoint).camera
        shot = next(s for s in self.shots if s.id == still.shot)
        return self.checkpoint(shot.from_cp).camera

    def must_not_exist(self, cp: Checkpoint) -> list[str]:
        """Every element a later checkpoint adds (derived, so it never drifts) plus the checkpoint's own not_yet."""
        i = [c.id for c in self.checkpoints].index(cp.id)
        later = [e for c in self.checkpoints[i + 1:] for e in c.built if e not in cp.built]
        return list(dict.fromkeys([*later, *cp.not_yet]))

    def shot_into(self, cp_id: str) -> "Shot | None":
        return next((s for s in self.shots if s.to_cp == cp_id), None)

    def dependents(self, still_key: str) -> list[str]:
        """Clips that start or end on this still."""
        return [c.key for c in self.clips() if still_key in (c.start_still, c.end_still)]

    # --- still briefs: the generation / edit prompt (also what to paste into ChatGPT for a manual override) ---
    BRIEF_NOT_YET_LOOKAHEAD = 3  # "must not appear" names only the next few steps: naming the whole future invites it

    def _lock(self, camera: str, *, first: bool = False, new_camera: bool = False) -> str:
        bible = (f"Location: {self.bibles.get('location', '')}. Builder (always the same person): "
                 f"{self.bibles.get('builder', '')}. Structure: {self.bibles.get('structure', '')}.")
        if first:
            return (f"Create a vertical 9:16 realistic documentary photograph, not an illustration. Camera: "
                    f"{self.cameras.get(camera, camera)}. {bible} Candid and unposed; the builder is working, not "
                    "looking at the camera. Add nothing that is not described.")
        if new_camera:
            return (f"Vertical 9:16. Show the build exactly as it stands in the attached approved still, from a new "
                    f"camera: {self.cameras.get(camera, camera)}. Every object, material and construction detail stays "
                    f"where it is in reality; only the viewpoint changes, plus anything the visible state below adds. "
                    f"The attached image is authoritative: the same structure, environment, builder, lighting and "
                    f"geometry, seen from the new camera. "
                    f"{bible} Realistic documentary photograph, not an illustration. Add nothing that is not described.")
        return (f"Vertical 9:16. Edit the attached approved still: same camera ({self.cameras.get(camera, camera)}) "
                f"with identical framing. {bible} The attached image is authoritative: keep its camera, framing, "
                "structure, environment, builder, lighting and geometry exactly; keep every pixel of the scene identical "
                "except the construction progress, the builder's position, tools and materials. Realistic documentary "
                "photograph, not an "
                "illustration. Nothing already built may disappear or regress; add nothing that is not described.")

    def _cp_brief(self, cp: Checkpoint) -> str:
        i = [c.id for c in self.checkpoints].index(cp.id)
        prev = self.checkpoints[i - 1] if i else None
        new = [e for e in cp.built if e not in self._previous_built(cp)]
        materials = "; ".join(f"{e}: from {cp.materials[e]}" for e in new if e in cp.materials)
        soon = [e for c in self.checkpoints[i + 1:i + 1 + self.BRIEF_NOT_YET_LOOKAHEAD] for e in c.built
                if e not in cp.built]
        not_yet = list(dict.fromkeys([*soon, *cp.not_yet]))
        lock = self._lock(cp.camera, first=prev is None, new_camera=prev is not None and prev.camera != cp.camera)
        return (f"{cp.id.upper()} - {cp.title}. {lock} Visible state: {cp.state} "
                f"{('Built so far: ' + ', '.join(cp.built) + '. ') if cp.built else ''}"
                f"{('Material sources in view: ' + materials + '. ') if materials else ''}"
                f"Builder action: {cp.action or 'as in the previous still'}. "
                f"Tools in view: {', '.join(cp.tools_in_view) or 'none'}. "
                f"{('Must NOT appear yet: ' + ', '.join(not_yet) + '.') if not_yet else ''}").strip()

    def _mid_brief(self, shot: Shot, n: int) -> str:
        cp_from, cp_to = self.checkpoint(shot.from_cp), self.checkpoint(shot.to_cp)
        done = shot.beats[n - 1]
        nxt = shot.beats[n]
        state = done.after or (f"the work of beat {n} is done ({done.task}, at {done.location}); the rest of the work "
                               f"toward {cp_to.id.upper()} is not done yet")
        not_yet = list(dict.fromkeys([*(e for e in cp_to.built if e not in cp_from.built), *cp_to.not_yet]))
        return (f"{shot.id} intermediate still {n} of {shot.clip_count - 1} ({shot.title}), between "
                f"{cp_from.id.upper()} and {cp_to.id.upper()}. {self._lock(cp_from.camera)} Visible state: {state}. "
                f"Builder action: in position for the next step - {nxt.task} ({nxt.location}), caught mid-work. "
                f"The rest of the work toward {cp_to.id.upper()} is NOT done yet"
                f"{(' - must NOT appear yet: ' + ', '.join(not_yet)) if not_yet else ''}.")

    def _previous_built(self, cp: Checkpoint) -> tuple[str, ...]:
        i = [c.id for c in self.checkpoints].index(cp.id)
        return self.checkpoints[i - 1].built if i > 0 else ()


def load_spec(path: Path) -> ProjectSpec:
    try:
        raw = json.loads(Path(path).read_text())
    except (OSError, ValueError) as e:
        raise SpecError(f"Cannot read project spec {path}: {e}") from e
    try:
        checkpoints = [Checkpoint(c["id"], c["title"], c["state"], c["camera"], tuple(c.get("built", ())),
                                  dict(c.get("materials", {})), tuple(c.get("tools_in_view", ())),
                                  c.get("action", ""), tuple(c.get("not_yet", ())))
                       for c in raw.get("checkpoints", [])]
        shots = [Shot(s["id"], s["from"], s["to"], s["title"], s["complexity"], s["shot_class"],
                      tuple(Beat(b["task"], b["location"], int(b.get("duration_seconds", 3)), b.get("after", ""))
                            for b in s.get("beats", [])),
                      bool(s.get("camera_moves", False)), bool(s.get("proof", False)), s.get("model"),
                      s.get("hold", ""))
                 for s in raw.get("shots", [])]
        spec = ProjectSpec(raw["slug"], raw["name"], raw["status"], float(raw["budget"]["cap_usd"]),
                           float(raw["budget"]["per_clip_max_usd"]), raw.get("concept"), dict(raw.get("bibles", {})),
                           dict(raw.get("cameras", {})), checkpoints, shots, _stills_config(raw.get("stills") or {}))
    except (KeyError, TypeError, ValueError) as e:
        raise SpecError(f"Project spec {path} is malformed: {e!r}") from e
    if spec.stills_config.source not in STILL_SOURCES:
        raise SpecError(f"stills.source must be one of {STILL_SOURCES}, not {spec.stills_config.source!r}")
    for shot in spec.shots:
        if shot.shot_class not in SHOT_CLASSES:
            raise SpecError(f"{shot.id}: unknown shot_class {shot.shot_class!r}")
        if shot.complexity not in COMPLEXITY_CLIPS:
            raise SpecError(f"{shot.id}: unknown complexity {shot.complexity!r}")
    return spec


def _stills_config(raw: dict) -> StillsConfig:
    d = StillsConfig()
    return StillsConfig(raw.get("source", d.source), raw.get("generate_model", d.generate_model),
                        raw.get("edit_model", d.edit_model), float(raw.get("per_still_max_usd", d.per_still_max_usd)),
                        tuple(raw.get("first_still_references", ())), tuple(raw.get("proof_stills", ())),
                        dict(raw.get("model_overrides", {})),
                        tuple(raw["frame_size"]) if raw.get("frame_size") else None)
